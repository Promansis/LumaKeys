#!/usr/bin/env bash
# Lists what changed between the last audited source identity and HEAD, grouped by
# audit surface, as Markdown. Read-only. Pair the output with
# docs/audit/templates/delta-inventory.md.
#
# Usage: scripts/audit/delta-inventory.sh [BASE_REF] [HEAD_REF]
#   BASE_REF defaults to the Phase 10 verification commit (0bd40f5).
#   HEAD_REF defaults to HEAD.
set -euo pipefail

BASE_REF="${1:-0bd40f5}"
HEAD_REF="${2:-HEAD}"
cd "$(dirname "$0")/../.."

base_sha="$(git rev-parse --short "$BASE_REF")"
head_sha="$(git rev-parse --short "$HEAD_REF")"
base_date="$(git log -1 --format=%ad --date=short "$BASE_REF")"
head_date="$(git log -1 --format=%ad --date=short "$HEAD_REF")"

classify() {
  case "$1" in
    src/server/*) echo "server" ;;
    src/main/*) echo "electron-main" ;;
    src/persistence/*|src/storage/*|src/lib/storage/*|src/lib/libraryBackup/*) echo "persistence" ;;
    src/shared/*) echo "bridge-contract" ;;
    src/renderer/webBridge*) echo "bridge-contract" ;;
    src/renderer/components/*) echo "renderer-ui" ;;
    src/renderer/*) echo "renderer-shell" ;;
    src/lib/game/*|src/lib/midi/*|src/lib/audio/*|src/lib/input/*|src/lib/theory/*|src/lib/learning/*) echo "practice-engine" ;;
    src/lib/*) echo "lib-other" ;;
    public/*) echo "public-assets" ;;
    scripts/*|packaging/*|Dockerfile|docker-compose.yml|.dockerignore|package.json|package-lock.json|*.config.ts|tsconfig*.json) echo "build-ops" ;;
    docs/audit/*) echo "audit-docs" ;;
    docs/*|*.md|DESIGN.json) echo "docs" ;;
    *) echo "other" ;;
  esac
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
git diff --name-status -M "$BASE_REF" "$HEAD_REF" > "$tmp"

echo "# Delta Inventory: ${base_sha} (${base_date}) -> ${head_sha} (${head_date})"
echo
echo "Generated by \`scripts/audit/delta-inventory.sh ${BASE_REF} ${HEAD_REF}\` on $(date +%F)."
echo
echo "## Commits"
echo
git log --format='- `%h` %ad %s' --date=short "${BASE_REF}..${HEAD_REF}"
echo
echo "## Changed Files By Surface"
echo
echo "| Surface | Added | Modified | Deleted/renamed | Test files touched |"
echo "|---|---:|---:|---:|---:|"

declare -A added modified removed tests
while IFS=$'\t' read -r status path newpath; do
  [ -z "${status:-}" ] && continue
  file="${newpath:-$path}"
  area="$(classify "$file")"
  case "${status:0:1}" in
    A) added[$area]=$(( ${added[$area]:-0} + 1 )) ;;
    M) modified[$area]=$(( ${modified[$area]:-0} + 1 )) ;;
    D|R) removed[$area]=$(( ${removed[$area]:-0} + 1 )) ;;
  esac
  case "$file" in *.test.ts|*.test.tsx) tests[$area]=$(( ${tests[$area]:-0} + 1 )) ;; esac
done < "$tmp"

for area in server electron-main persistence bridge-contract renderer-shell renderer-ui practice-engine lib-other public-assets build-ops audit-docs docs other; do
  a="${added[$area]:-0}"; m="${modified[$area]:-0}"; r="${removed[$area]:-0}"; t="${tests[$area]:-0}"
  if [ "$a" != 0 ] || [ "$m" != 0 ] || [ "$r" != 0 ]; then
    echo "| ${area} | ${a} | ${m} | ${r} | ${t} |"
  fi
done

echo
echo "## New Source Files (new surfaces to inventory)"
echo
awk -F'\t' '$1=="A" && $2 ~ /^src\// && $2 !~ /\.test\.tsx?$/ {print "- `" $2 "`"}' "$tmp" | sort
echo
echo "## Modified Source Files Without A Touched Test"
echo
awk -F'\t' '$1=="M" && $2 ~ /^src\// && $2 !~ /\.test\.tsx?$/ {print $2}' "$tmp" | sort > "$tmp.mod"
awk -F'\t' '$2 ~ /\.test\.tsx?$/ {print $2}' "$tmp" | sed -E 's/\.test\.(tsx?)$/.\1/' | sort > "$tmp.tested"
comm -23 "$tmp.mod" "$tmp.tested" | sed 's/^/- `/; s/$/`/'
rm -f "$tmp.mod" "$tmp.tested"
echo
echo "## Deleted Or Renamed Paths"
echo
awk -F'\t' '$1 ~ /^(D|R)/ {printf "- `%s`", $2; if ($3 != "") printf " -> `%s`", $3; print ""}' "$tmp" | sort
