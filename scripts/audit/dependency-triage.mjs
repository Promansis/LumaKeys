#!/usr/bin/env node
// Splits `npm audit` advisories into production-reachable and build/dev-only sets and
// prints a Markdown triage table. Advisories are leads, not findings: a production
// advisory becomes a finding only after reachability is shown (see charter).
//
// Usage:
//   node scripts/audit/dependency-triage.mjs                 # run npm audit (needs registry access)
//   node scripts/audit/dependency-triage.mjs --out FILE.md   # also write the Markdown to FILE
//   node scripts/audit/dependency-triage.mjs --from all.json --from-prod prod.json
//        # use saved `npm audit --json` and `npm audit --json --omit=dev` outputs
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '../..');
const argv = process.argv.slice(2);
const option = (name) => {
  const index = argv.indexOf(name);
  return index === -1 ? undefined : argv[index + 1];
};

function runAudit(extraArgs) {
  const result = spawnSync('npm', ['audit', '--json', ...extraArgs], {
    cwd: projectRoot,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) {
    throw result.error;
  }
  const text = result.stdout.trim();
  if (!text.startsWith('{')) {
    throw new Error(`npm audit ${extraArgs.join(' ')} returned no JSON:\n${result.stderr}`);
  }
  return JSON.parse(text);
}

function load(path) {
  return JSON.parse(readFileSync(resolve(projectRoot, path), 'utf8'));
}

const all = option('--from') ? load(option('--from')) : runAudit([]);
const prod = option('--from-prod') ? load(option('--from-prod')) : runAudit(['--omit=dev']);

const SEVERITY_ORDER = { critical: 0, high: 1, moderate: 2, low: 3, info: 4 };
const bySeverity = (a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity] || a.name.localeCompare(b.name);

function advisoryRows(report) {
  return Object.values(report.vulnerabilities ?? {})
    .map((v) => {
      const direct = (v.via ?? []).filter((item) => typeof item === 'object');
      return {
        name: v.name,
        severity: v.severity,
        range: v.range ?? '',
        isDirect: v.isDirect ? 'direct' : 'transitive',
        fix: v.fixAvailable === true ? 'yes' : v.fixAvailable ? `major: ${v.fixAvailable.name}@${v.fixAvailable.version}` : 'no',
        advisories: direct.map((item) => `[${item.title}](${item.url})`).join('<br>') || `via ${(v.via ?? []).join(', ')}`,
      };
    })
    .sort(bySeverity);
}

// devDependencies that are nevertheless shipped to users: Electron is the desktop runtime.
const SHIPPED_DEV_PACKAGES = new Set(['electron']);

const prodRows = advisoryRows(prod);
const prodNames = new Set(prodRows.map((row) => row.name));
const shippedRows = advisoryRows(all).filter((row) => !prodNames.has(row.name) && SHIPPED_DEV_PACKAGES.has(row.name));
const devRows = advisoryRows(all).filter((row) => !prodNames.has(row.name) && !SHIPPED_DEV_PACKAGES.has(row.name));

function countTable(meta) {
  const v = meta.vulnerabilities ?? {};
  return `| ${v.critical ?? 0} | ${v.high ?? 0} | ${v.moderate ?? 0} | ${v.low ?? 0} | ${v.total ?? 0} |`;
}

const lines = [];
lines.push(`# Dependency Triage: ${new Date().toISOString().slice(0, 10)}`);
lines.push('');
lines.push('Generated by `scripts/audit/dependency-triage.mjs`. Advisories are leads until reachability is evidenced.');
lines.push('');
lines.push('| Scope | Critical | High | Moderate | Low | Total |');
lines.push('|---|---:|---:|---:|---:|---:|');
lines.push(`| All dependencies | ${countTable(all.metadata).slice(2)}`);
lines.push(`| Production only (\`--omit=dev\`) | ${countTable(prod.metadata).slice(2)}`);
lines.push('');
lines.push('## Production Advisories (reachability review required)');
lines.push('');
lines.push('| Package | Severity | Vulnerable range | Dependency | Fix | Advisory | Reachable in LumaKeys? |');
lines.push('|---|---|---|---|---|---|---|');
if (prodRows.length === 0) {
  lines.push('| _none_ | | | | | | |');
}
for (const row of prodRows) {
  lines.push(`| ${row.name} | ${row.severity} | ${row.range} | ${row.isDirect} | ${row.fix} | ${row.advisories} | TBD |`);
}
lines.push('');
lines.push('## Desktop Runtime Advisories (devDependency, but shipped in the Electron package)');
lines.push('');
lines.push('| Package | Severity | Vulnerable range | Fix | Advisory | Reachable in LumaKeys? |');
lines.push('|---|---|---|---|---|---|');
if (shippedRows.length === 0) {
  lines.push('| _none_ | | | | | |');
}
for (const row of shippedRows) {
  lines.push(`| ${row.name} | ${row.severity} | ${row.range} | ${row.fix} | ${row.advisories} | TBD |`);
}
lines.push('');
lines.push('## Build And Development Chain Advisories');
lines.push('');
lines.push('These do not ship in the Electron bundle or the web server image. Record them as');
lines.push('operations leads (developer-machine and CI exposure), not product findings.');
lines.push('');
lines.push('| Package | Severity | Dependency | Fix |');
lines.push('|---|---|---|---|');
for (const row of devRows) {
  lines.push(`| ${row.name} | ${row.severity} | ${row.isDirect} | ${row.fix} |`);
}
lines.push('');

const markdown = lines.join('\n');
const out = option('--out');
if (out) {
  writeFileSync(resolve(projectRoot, out), markdown);
  console.log(`Wrote ${resolve(projectRoot, out)}`);
} else {
  console.log(markdown);
}
